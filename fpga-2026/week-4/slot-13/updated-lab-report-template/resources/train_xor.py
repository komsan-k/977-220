"""Reproducible integer perceptron training for a 2-2-1 XOR ANN.

Supervised intermediate labels: H1=OR(A,B), H2=NAND(A,B), Y=AND(H1,H2).
This is neuron-wise perceptron training, not end-to-end backpropagation.
Run from any directory: python train_xor.py
"""
from pathlib import Path
import csv

ROOT = Path(__file__).resolve().parents[1]
X = [(0, 0), (0, 1), (1, 0), (1, 1)]


def step(z):
    return int(z > 0)


def train_perceptron(inputs, labels, max_epochs=200):
    w = [0, 0, 0]  # w1, w2, bias; integer updates
    for epoch in range(1, max_epochs + 1):
        errors = 0
        for (a, b), expected in zip(inputs, labels):
            predicted = step(w[0] * a + w[1] * b + w[2])
            delta = expected - predicted
            if delta:
                w[0] += delta * a
                w[1] += delta * b
                w[2] += delta
                errors += 1
        if errors == 0:
            return tuple(w), epoch
    raise RuntimeError("Perceptron failed to converge")


h1_targets = [a | b for a, b in X]
h2_targets = [1 - (a & b) for a, b in X]
w1, e1 = train_perceptron(X, h1_targets)
w2, e2 = train_perceptron(X, h2_targets)
hidden = [(step(w1[0]*a+w1[1]*b+w1[2]),
           step(w2[0]*a+w2[1]*b+w2[2])) for a,b in X]
wy, ey = train_perceptron(hidden, [a & b for a,b in hidden])
weights = (w1, w2, wy)

# Emit Verilog declarations for inclusion INSIDE each ANN core module.
labels = ('W11','W12','B1','W21','W22','B2','WO1','WO2','BO')
values = [v for triple in weights for v in triple]
assert all(-128 <= v <= 127 for v in values)
lines = ["// Auto-generated by python/train_xor.py; do not edit by hand."]
for label, value in zip(labels, values):
    lit = f"-8'sd{abs(value)}" if value < 0 else f"8'sd{value}"
    lines.append(f"localparam signed [7:0] {label} = {lit};")
(ROOT/'rtl'/'ann_weights.vh').write_text('\n'.join(lines)+'\n', encoding='utf-8')

with (ROOT/'training_results.csv').open('w', newline='', encoding='utf-8') as f:
    writer = csv.writer(f)
    writer.writerow(['A','B','H1','H2','Y','Expected_XOR','Match'])
    for (a,b),(h1,h2) in zip(X,hidden):
        y = step(wy[0]*h1 + wy[1]*h2 + wy[2])
        writer.writerow([a,b,h1,h2,y,a^b,int(y == (a^b))])
        assert y == (a ^ b)

print('Training epochs:', e1, e2, ey)
for name, params in zip(('H1','H2','Y'), weights):
    print(f'{name}: w1={params[0]}, w2={params[1]}, b={params[2]}')
print('All four XOR predictions pass.')
print('Generated rtl/ann_weights.vh and training_results.csv')
