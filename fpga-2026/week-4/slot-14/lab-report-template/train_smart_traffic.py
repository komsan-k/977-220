#!/usr/bin/env python3
"""Train the small 2-3-2 threshold ANN used in Topic-14 Smart Traffic.

Pure Python 3, no external dependencies.

The 256-row dataset is SYNTHETIC: labels reproduce the existing teaching RTL,
not observed traffic. Hidden units have tied unit weights (A+B) and learn their
integer thresholds by exhaustive supervised calibration. The two output units
are trained with the perceptron rule on the three hidden-unit activations.
This is NOT end-to-end gradient-descent training.
"""
from __future__ import annotations

import argparse
import csv
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIELDS = ["road_a", "road_b", "total", "h1_target", "h2_target",
          "h3_target", "y1_target", "y0_target", "traffic_class", "green_time"]


def teacher(a: int, b: int) -> dict[str, int | str]:
    total = a + b
    h1, h2, h3 = (int(total >= t) for t in (5, 9, 13))
    cls = "10" if h2 or h3 else ("01" if h1 else "00")
    return {"road_a": a, "road_b": b, "total": total,
            "h1_target": h1, "h2_target": h2, "h3_target": h3,
            "y1_target": int(cls[0]), "y0_target": int(cls[1]),
            "traffic_class": cls,
            "green_time": {"00": 10, "01": 20, "10": 30}[cls]}


def write_dataset(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDS)
        writer.writeheader()
        for a in range(16):
            for b in range(16):
                writer.writerow(teacher(a, b))


def load_dataset(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames != FIELDS:
            raise ValueError(f"Unexpected CSV columns: {reader.fieldnames}")
        rows = []
        for raw in reader:
            row = {k: (raw[k] if k == "traffic_class" else int(raw[k]))
                   for k in FIELDS}
            if not (0 <= row["road_a"] <= 15 and 0 <= row["road_b"] <= 15):
                raise ValueError(f"Out-of-range 4-bit input: {row}")
            rows.append(row)
    if len(rows) != 256 or len({(r['road_a'], r['road_b']) for r in rows}) != 256:
        raise ValueError("Dataset must contain exactly the 256 unique 4-bit input pairs")
    return rows


def step(z: int) -> int:
    return int(z > 0)


def fit_threshold(rows: list[dict], target: str) -> int:
    # Hidden weights wA=wB=1 are fixed by the symmetric sum-based architecture.
    # Fit T in step(A+B-(T-1)) from the supervised hidden target column.
    scored = []
    for threshold in range(32):
        errors = sum(int(r["total"] >= threshold) != r[target] for r in rows)
        scored.append((errors, threshold))
    errors, threshold = min(scored)
    if errors:
        raise RuntimeError(f"Cannot fit hidden threshold for {target}: {errors} errors")
    return threshold


def train_output(rows: list[dict], hidden: list[tuple[int, int, int]],
                 target: str, seed: int) -> tuple[list[int], int, int]:
    rng = random.Random(seed)
    w = [0, 0, 0]
    bias = 0
    order = list(range(len(rows)))
    for epoch in range(1, 1001):
        rng.shuffle(order)
        for i in order:
            features = hidden[i]
            prediction = step(sum(wj * hj for wj, hj in zip(w, features)) + bias)
            delta = rows[i][target] - prediction
            if delta:
                for j in range(3):
                    w[j] += delta * features[j]
                bias += delta
        mistakes = sum(
            step(sum(wj * hj for wj, hj in zip(w, hidden[i])) + bias) != r[target]
            for i, r in enumerate(rows)
        )
        if mistakes == 0:
            return w, bias, epoch
    raise RuntimeError(f"Output perceptron {target} did not converge")


def infer(a: int, b: int, thresholds: list[int], outputs: dict):
    hs = tuple(step(a + b - (t - 1)) for t in thresholds)
    bits = {}
    for name in ("y1", "y0"):
        w, bias = outputs[name]
        bits[name] = step(sum(wj * hj for wj, hj in zip(w, hs)) + bias)
    cls = f"{bits['y1']}{bits['y0']}"
    duration = {"00": 10, "01": 20, "10": 30}.get(cls, 10)
    return hs, cls, duration


def make_verilog(thresholds: list[int], outputs: dict) -> str:
    lines = [
        "// Auto-generated by train_smart_traffic.py; do not edit manually.",
        "// Synthetic supervised training reproduces the Topic-14 threshold rules.",
        "module smart_traffic_ai_trained (",
        "    input wire [3:0] road_a,",
        "    input wire [3:0] road_b,",
        "    output wire [1:0] traffic_class,",
        "    output reg [5:0] green_time",
        ");",
        "    wire signed [15:0] a_s = $signed({1'b0, road_a});",
        "    wire signed [15:0] b_s = $signed({1'b0, road_b});",
    ]
    for i, threshold in enumerate(thresholds, 1):
        lines.append(f"    localparam signed [7:0] H{i}_WA = 8'sd1;")
        lines.append(f"    localparam signed [7:0] H{i}_WB = 8'sd1;")
        lines.append(f"    localparam signed [7:0] H{i}_B = -8'sd{threshold - 1};")
        lines.append(f"    wire signed [15:0] z_h{i} = a_s * H{i}_WA + b_s * H{i}_WB + H{i}_B;")
        lines.append(f"    wire h{i} = (z_h{i} > 0);")
    for i in range(1, 4):
        lines.append(f"    wire signed [15:0] h{i}_s = {{15'b0, h{i}}};")
    for name in ("y1", "y0"):
        w, bias = outputs[name]
        prefix = name.upper()
        for j, weight in enumerate(w, 1):
            value = f"-8'sd{abs(weight)}" if weight < 0 else f"8'sd{weight}"
            lines.append(f"    localparam signed [7:0] {prefix}_W{j} = {value};")
        bv = f"-8'sd{abs(bias)}" if bias < 0 else f"8'sd{bias}"
        lines.append(f"    localparam signed [7:0] {prefix}_B = {bv};")
        lines.append(f"    wire signed [15:0] z_{name} = h1_s * {prefix}_W1 + h2_s * {prefix}_W2 + h3_s * {prefix}_W3 + {prefix}_B;")
        lines.append(f"    wire {name} = (z_{name} > 0);")
    lines += [
        "    assign traffic_class = {y1, y0};",
        "    always @(*) begin",
        "        case (traffic_class)",
        "            2'b00: green_time = 6'd10;",
        "            2'b01: green_time = 6'd20;",
        "            2'b10: green_time = 6'd30;",
        "            default: green_time = 6'd10;",
        "        endcase",
        "    end",
        "endmodule",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--data", type=Path, default=HERE / "smart_traffic_dataset.csv")
    p.add_argument("--out", type=Path, default=HERE)
    p.add_argument("--regenerate-data", action="store_true")
    args = p.parse_args()
    if args.regenerate_data or not args.data.exists():
        write_dataset(args.data)
    rows = load_dataset(args.data)
    thresholds = [fit_threshold(rows, f"h{i}_target") for i in range(1, 4)]
    hidden = [tuple(step(r["total"] - (t - 1)) for t in thresholds) for r in rows]
    y1_w, y1_b, y1_epochs = train_output(rows, hidden, "y1_target", seed=14)
    y0_w, y0_b, y0_epochs = train_output(rows, hidden, "y0_target", seed=15)
    outputs = {"y1": (y1_w, y1_b), "y0": (y0_w, y0_b)}
    args.out.mkdir(parents=True, exist_ok=True)
    results_path = args.out / "training_results.csv"
    failures = 0
    with results_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["road_a", "road_b", "expected_class", "predicted_class",
                         "expected_green_time", "predicted_green_time", "pass"])
        for row in rows:
            hs, cls, duration = infer(row["road_a"], row["road_b"], thresholds, outputs)
            correct = (cls == row["traffic_class"] and duration == row["green_time"]
                       and hs == tuple(row[f"h{i}_target"] for i in range(1, 4)))
            failures += not correct
            writer.writerow([row["road_a"], row["road_b"], row["traffic_class"],
                             cls, row["green_time"], duration, int(correct)])
    params = []
    for i, t in enumerate(thresholds, 1):
        params += [f"H{i}_WA = 1", f"H{i}_WB = 1", f"H{i}_B = {1-t}"]
    for name in ("y1", "y0"):
        w, b = outputs[name]
        params += [f"{name.upper()}_W{j} = {v}" for j, v in enumerate(w, 1)]
        params.append(f"{name.upper()}_B = {b}")
    (args.out / "trained_parameters.txt").write_text("\n".join(params) + "\n", encoding="utf-8")
    (args.out / "rtl").mkdir(exist_ok=True)
    (args.out / "rtl" / "smart_traffic_ai_trained.v").write_text(
        make_verilog(thresholds, outputs), encoding="utf-8")
    print("Training source: 256 synthetic, exhaustively enumerated labeled cases")
    print("Hidden weights: fixed (1, 1); learned thresholds:", thresholds)
    print("Output Y1 weights, bias, epochs:", y1_w, y1_b, y1_epochs)
    print("Output Y0 weights, bias, epochs:", y0_w, y0_b, y0_epochs)
    print(f"Exhaustive reproduction: {256 - failures}/256 correct")
    print("Saved:", results_path, args.out / "trained_parameters.txt",
          args.out / "rtl" / "smart_traffic_ai_trained.v", sep="\n  ")
    if failures:
        raise SystemExit(f"ERROR: {failures} of 256 cases failed")


if __name__ == "__main__":
    main()
